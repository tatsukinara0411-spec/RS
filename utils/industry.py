"""
求人の本文（カードの文字）から業種を判定する。

検索キーワードの業種をそのまま付けると、カラオケ店や菓子店が「警備」になるなど
ずれが出るため、カードの文字に業種のキーワードが含まれるかで判定し直す。

判定の順番:
  1. 検索した業種のキーワードが含まれる → その業種
  2. 他の業種のキーワードが含まれる     → その業種（最初に一致したもの）
  3. どれも含まれない                   → 「その他」
  カードの文字が取れていない場合は、検索した業種のままにする。
"""
import unicodedata

INDUSTRY_KEYWORDS: dict[str, list[str]] = {
    "警備": ["警備", "ガードマン", "交通誘導", "誘導員", "保安", "巡回", "施設管理員", "監視員"],
    "運輸": ["ドライバー", "運転手", "配送", "配達", "運送", "運輸", "物流", "トラック",
             "タクシー", "引越", "仕分け", "ピッキング", "倉庫"],
    "外食": ["飲食", "ホール", "キッチン", "調理", "居酒屋", "カフェ", "レストラン", "ラーメン",
             "寿司", "焼肉", "ファミレス", "ファストフード", "洗い場", "バリスタ", "カラオケ"],
    "販売": ["販売", "接客", "レジ", "店員", "ショップ", "アパレル", "スーパー", "コンビニ",
             "ドラッグストア", "品出し", "携帯", "家電量販"],
    "介護": ["介護", "ヘルパー", "ケアワーカー", "デイサービス", "老人ホーム", "グループホーム",
             "福祉", "看護助手", "生活支援員", "訪問入浴"],
    "建設": ["建設", "建築", "土木", "施工", "現場作業", "解体", "内装", "電気工事", "設備工事",
             "塗装", "足場", "大工", "鳶", "とび職", "左官", "配管"],
}

OTHER = "その他"


def classify_industry(text: str, searched: str) -> str:
    if not text or not text.strip():
        return searched
    t = unicodedata.normalize("NFKC", text)
    if any(k in t for k in INDUSTRY_KEYWORDS.get(searched, [])):
        return searched
    for name, kws in INDUSTRY_KEYWORDS.items():
        if name != searched and any(k in t for k in kws):
            return name
    return OTHER
